/*
 * Overworld wild encounters.
 *
 * Wild Pokemon are generated by the game's own encounter code, then shown as walking map
 * objects; touching one starts a battle against exactly that Pokemon. The expensive work
 * (generating Pokemon, creating map objects) is spread in small batches so the game never
 * stutters.
 *
 * Two things limit how many Pokemon a place shows:
 *   - the density rule: each patch of tiles with the same metatile behaviour holds one Pokemon
 *     for every OWENC_FILL_DIV tiles of its own size (a patch of 10 tiles holds 3, a patch of 12
 *     holds 4, three separated grass patches are three patches with their own target);
 *   - the global budget: the manager slots we got, minus what the game's own object events need.
 * One attempt is made every OWENC_SPAWN_INTERVAL frames until both are full.
 *
 * A spawn does not come from a player step: OwEnc_SpawnOne calls the game's encounter generator
 * directly, so Pokemon keep appearing while the player stands still.
 *
 * Nothing of ours is saved. A place is deleted when the player leaves it (new map, building,
 * cave exit) and regenerated from scratch when he comes back; inside a place nothing despawns
 * except the Pokemon that fought.
 *
 * A Pokemon is an OwEnc record; its map object lives as long as the map does. At contact the
 * Pokemon is rebuilt from the record with the same PID, OT ID and IVs.
 *
 * Fights start two ways: the player pushes into a Pokemon, or a Pokemon walks into him (it
 * turns first, then hits). A Pokemon never walks onto the player or the follower.
 *
 * Hooks (see the "hooks" file):
 *   OwEnc_CheckWildEncounter  replaces FieldSystem_CheckWildEncounter (end of every step)
 *   OwEnc_FrameHook           runs OwEnc_Frame every frame (inside FieldInput_Process)
 *   OwEnc_Capture             replaces sub_02050B08 (the "start wild battle" function)
 *   OwEnc_BattleDone          replaces sub_02050724 (called right after a battle)
 *   OwEnc_ManagerInit         replaces MapObjectManager_Init (bigger map-object array)
 *   OwEnc_SyncToSaveEx        replaces the map-object save sync (skips our wild Pokemon)
 *
 * Sections, in order: tuning, data, util, slot counting, battle candidates, record <->
 * Pokemon, lifecycle, map object, shiny look, terrain, follower, battle, sync, moving,
 * player contact, spawn, save, manager, frame.
 */

