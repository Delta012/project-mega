/* One heap block holds the records, the generator slot table and the generator state: .data is too
   small for them, and it is zeroed by hand here because .bss is never zeroed in this overlay. */
static void OwEnc_Ensure(void){
    if (sOwEnc) return;
    unsigned bytes = sizeof(OwEnc) * OWENC_SLOTS
                   + sizeof(struct EncounterSlot) * OWENC_GEN_SLOTS
                   + sizeof(struct EncounterGenState);
    u32 *w = (u32 *)sys_AllocMemory(3, bytes);   /* HEAPID_MAIN_HEAP */
    if (!w) return;
    for (unsigned i = 0; i < bytes / 4; i++) w[i] = 0;
    sOwEnc    = (OwEnc *)w;
    sEncSlots = (struct EncounterSlot *)(w + (sizeof(OwEnc) * OWENC_SLOTS) / 4);
    sGenState = (struct EncounterGenState *)(w + (sizeof(OwEnc) * OWENC_SLOTS
                   + sizeof(struct EncounterSlot) * OWENC_GEN_SLOTS) / 4);
}

/* ===== model preload =====
   Replaces the map's model-ID fetch (ov1 FetchMapObjectsToPreload, 0x021E6644) with the same
   logic plus the model IDs of our shinies, so they render in 3D too. The pool can hold more live
   objects than OWENC_MODEL_MAX because several objects may share one species key: only distinct
   species need a key-table entry. */
#define OWENC_PRELOAD_MAX      24   /* MAX_MAP_OBJECTS_TO_PRELOAD (field_system.h): sizes the pending-load pool */
#define OWENC_GAME_KEY_MAX     2    /* real ids the game can key: its texture and palette share is 2
                                       (patched at 0x21F946A) and its model share is this + 3, so we must
                                       not write more. The game's insert asserts instead of failing when
                                       the region it writes is full (ov01_021F9B10 / 021F9C34 / 021F9D5C),
                                       and the caller then uses a NULL resource -- that is the hang on a
                                       route whose model bank lists more than 2 ids. Raise this together
                                       with the bytereplacement patch at 0x21F946A. */
#define OWENC_PRELOAD_SHINY    1    /* also ask for the model IDs of our shinies */
#define OWENC_PRELOAD_SENTINEL 0xFFFF /* MAP_OBJECT_PRELOAD_SENTINEL */
typedef struct {
    u16 count;
    int ids[OWENC_PRELOAD_MAX + 1];  /* +1 for the sentinel */
} OwEncPreload;

OwEncPreload *OwEnc_FetchMapObjectsToPreload(u32 heapID, u16 modelBank){
    OwEnc_Ensure();
    OwEncPreload *r = (OwEncPreload *)Heap_Alloc(heapID, sizeof(OwEncPreload));
    if (!r) return NULL;
    u16 *list = AllocAtEndAndReadWholeNarcMemberByIdPair(92 /* NARC_a_0_9_2 */, modelBank, heapID);
    int n = 0;
    if (list) {
        /* ov01_021F9980 keys each id in the game's own share of the key tables. More than
           OWENC_GAME_KEY_MAX real ids makes the game's insert assert, so we stop there; the species
           we show are asked for on demand by OwEnc_ModelLoaded. Raise OWENC_GAME_KEY_MAX together
           with the bytereplacement patches. */
        /* The sentinel is not an id: the game stops reading the list there, so the ids actually
           inserted are at most OWENC_GAME_KEY_MAX. The reported count is separate and only sizes the
           game's per-species entries array, which must be at least the model-load cap. */
        for (int i = 0; i < OWENC_GAME_KEY_MAX; i++) {
            if (list[i] == OWENC_PRELOAD_SENTINEL) break;
            r->ids[n++] = list[i];
        }
        Heap_Free(list);
    }
#if OWENC_PRELOAD_SHINY
    for (int i = 0; i < OWENC_SLOTS && n < OWENC_GAME_KEY_MAX; i++) {
        if (sOwEnc[i].state == SLOT_ACTIVE && sOwEnc[i].shiny) r->ids[n++] = sOwEnc[i].sprite;
    }
#endif
    r->ids[n] = OWENC_PRELOAD_SENTINEL;
    r->count = n;
    return r;
}

/* ===== util ===== */

/* Player coordinates may come back as tiles or as 16.16 fixed point: accept both. */
static int OwEnc_TileFromAny(int v){
    if (v < 0) v = -v;
    return (v >= 65536) ? (v >> 16) : v;
}
static int OwEnc_Abs(int v){ return v < 0 ? -v : v; }

/* TRUE if tile (x,z) is inside the visible window */
static BOOL OwEnc_InWindow(int x, int z){
    return OwEnc_Abs(x - sPX) <= OWENC_WIN_X && OwEnc_Abs(z - sPZ) <= OWENC_WIN_Z;
}

/* Safari Zone and Bug Contest keep the classic encounters: their battle setup is different. */
static BOOL OwEnc_SpecialZone(FieldSystem *fs){
    void *flags = Ow_Save_VarsFlags_Get(fs->savedata);
    return Ow_CheckSafari(flags) || Ow_CheckBugContest(flags);
}

/* followMon sits at 0xE4 in FieldSystem; its first field is the follower's map object. */
static LocalMapObject *OwEnc_FollowerObj(FieldSystem *fs){
    if (!fs->followMon.active) return NULL;
    return *(LocalMapObject **)((u8 *)fs + 0xE4);
}

/* Reads the player and follower tiles once per frame. */
static void OwEnc_UpdatePlayer(FieldSystem *fs){
    sPX = OwEnc_TileFromAny(PlayerAvatar_GetXCoord(fs->playerAvatar));
    sPZ = OwEnc_TileFromAny(PlayerAvatar_GetZCoord(fs->playerAvatar));
    LocalMapObject *o = OwEnc_FollowerObj(fs);
    sHasFol = (o != NULL);
    if (o) {
        sFolX = (int)MapObject_GetCurrentX(o);
        sFolZ = (int)MapObject_GetCurrentY(o);   /* hg-engine's "Y" is the Z axis */
    }
}

/* ===== slot counting ===== */
static int OwEnc_Count(BOOL shiny){
    int n = 0;
    for (int i = 0; i < OWENC_SLOTS; i++)
        if (sOwEnc[i].state != SLOT_EMPTY && (sOwEnc[i].shiny != 0) == shiny) n++;
    return n;
}
static int OwEnc_FindFree(void){
    for (int i = 0; i < OWENC_SLOTS; i++) if (sOwEnc[i].state == SLOT_EMPTY) return i;
    return -1;
}

/* ===== battle candidates ===== */

/* Pokemon idx wants to start a battle this frame. The highest priority wins; among equal
   priorities one is picked at random (each has the same chance). */
static void OwEnc_Offer(int idx, int prio){
    if (prio < sHitPrio) return;
    if (prio > sHitPrio) { sHitPrio = prio; sHitIdx = idx; sHitTies = 1; return; }
    sHitTies++;
    if (gf_rand() % sHitTies == 0) sHitIdx = idx;
}

/* ===== record <-> Pokemon ===== */

/* Stores a generated wild Pokemon in the slot. Box attributes must be read through
   GetBoxMonData: GetMonData reads the raw blocks and returns garbage while the Pokemon is
   still encrypted. */
static void OwEnc_Pack(OwEnc *e, struct PartyPokemon *mon){
    struct BoxPokemon *b = &mon->box;
    e->pid       = GetBoxMonData(b, MON_DATA_PERSONALITY, 0);
    e->otId      = GetBoxMonData(b, MON_DATA_OTID, 0);
    e->ivs       = 0;
    for (int k = 0; k < 6; k++)
        e->ivs |= (GetBoxMonData(b, sIvField[k], 0) & 31) << (5 * k);
    e->species   = (u16)GetBoxMonData(b, MON_DATA_SPECIES, 0);
    e->form      = (u8)GetBoxMonData(b, MON_DATA_FORM, 0);
    e->level     = (u8)GetBoxMonData(b, MON_DATA_MET_LEVEL, 0);
    e->item      = (u16)GetBoxMonData(b, MON_DATA_HELD_ITEM, 0);
    e->ability   = (u16)GetBoxMonData(b, MON_DATA_ABILITY, 0);
    e->hidden113 = (u8)GetBoxMonData(b, MON_DATA_RESERVED_113, 0);
    e->hidden114 = (u16)GetBoxMonData(b, MON_DATA_RESERVED_114, 0);
    e->gender    = Ow_GetMonGender(mon);   /* pure: it does not write the gender block */
    e->shiny     = MonIsShiny(mon) ? 1 : 0;
}

/* Rebuilds the Pokemon from the slot: fixed PID and OT ID keep nature, gender and shininess
   exactly as the game generated them. */
static void OwEnc_Rebuild(const OwEnc *e, struct PartyPokemon *mon){
    u32 v;
    ZeroMonData(mon);
    PokeParaSet(mon, e->species, e->level, 32, TRUE, e->pid, ID_SET, e->otId);
    for (int k = 0; k < 6; k++) {
        v = (e->ivs >> (5 * k)) & 31;
        SetMonData(mon, sIvField[k], &v);
    }
    v = e->item;      SetMonData(mon, MON_DATA_HELD_ITEM, &v);
    v = e->form;      SetMonData(mon, MON_DATA_FORM, &v);
    if (e->form) InitBoxMonMoveset(&mon->box);   /* different forms can have different learnsets */
    v = e->hidden113; SetMonData(mon, MON_DATA_RESERVED_113, &v);
    v = e->hidden114; SetMonData(mon, MON_DATA_RESERVED_114, &v);
    v = e->ability;   SetMonData(mon, MON_DATA_ABILITY, &v);
    Ow_CalcMonStats(mon);                        /* IVs changed: stats must be recalculated */
}

/* ===== lifecycle ===== */
static void OwEnc_Forget(OwEnc *e){
    if (e->shinyBuf){                            /* our shiny gfx copy is heap memory */
        Heap_Free((u32 *)e->shinyBuf - 1);
        e->shinyBuf = 0;
    }
    if (sGroups && e->group) sGroups->fill[e->group - 1]--;  /* give the patch its slot back */
    u32 *p = (u32 *)e;                           /* clear the whole record */
    for (u32 i = 0; i < (sizeof(OwEnc) + 3) / 4; i++) p[i] = 0;
    e->mapId = 0xFFFF;
    e->dir = 1;
}
/* The object pointer may be stale after a field rebuild: check the sprite still matches. */
static BOOL OwEnc_ObjValid(OwEnc *e){
    return e->obj && (u32)MapObject_GetGfxID(e->obj) == e->sprite;
}
static void OwEnc_RemoveObj(OwEnc *e){
    if (OwEnc_ObjValid(e)) Ow_MapObject_Remove(e->obj);
    e->obj = NULL;
    e->walking = 0;
    e->aim = 0;
}
static void OwEnc_FreeSlot(OwEnc *e){
    OwEnc_RemoveObj(e);
    OwEnc_Forget(e);
}

/* How many pool slots are currently taken by a live map object. The rest of the records stay
   object-less (still in memory) and get an object as soon as a slot is given back. */
static int OwEnc_PoolUsed(void){
    int n = 0;
    for (int i = 0; i < OWENC_SLOTS; i++) if (OwEnc_ObjValid(&sOwEnc[i])) n++;
    return n;
}
static int OwEnc_Dist(const OwEnc *e){
    return OwEnc_Abs(e->curX - sPX) + OwEnc_Abs(e->curZ - sPZ);
}

/* Active record that holds a pool object and is farthest from the player (-1 if none). Battle
   records are skipped: their object must survive until the battle is over. Measured in the same
   pass as the nearest record without an object (see OwEnc_Populate), so the place is walked once. */

/* Object IDs, chosen once at spawn and stored in the record: they must not depend on the
   other slots, or a neighbour disappearing would change them. Nothing of ours is saved, so
   IDs above 0xFF are fine. */
static u16 OwEnc_RegularID(int i){
    return (u16)(i < OWENC_ID_SPLIT ? (OWENC_OBJ_ID + i) : (OWENC_BIG_ID_BASE + (i - OWENC_ID_SPLIT)));
}
static BOOL OwEnc_IsOurID(u32 id){
    return (id >= OWENC_OBJ_ID && id < OWENC_OBJ_ID + OWENC_ID_SPLIT)
        || (id >= OWENC_BIG_ID_BASE && id < OWENC_BIG_ID_BASE + OWENC_SLOTS);
}
static int OwEnc_SlotOfID(u32 id){
    if (!sOwEnc || !OwEnc_IsOurID(id)) return -1;
    for (int i = 0; i < OWENC_SLOTS; i++)
        if (sOwEnc[i].state != SLOT_EMPTY && sOwEnc[i].objId == id) return i;
    return -1;
}

/* Remove every object with this ID, even if we lost the pointer (they carry the KEEP flag,
   so the game would not remove them by itself). */
static void OwEnc_PurgeID(FieldSystem *fs, u32 id){
    LocalMapObject *prev = NULL;
    for (int n = 0; n < 4; n++) {
        LocalMapObject *o = GetMapObjectByID(fs->mapObjectMan, id);
        if (!o || o == prev) break;     /* none left, or removal did not work: stop */
        Ow_MapObject_Remove(o);
        prev = o;
    }
}
static void OwEnc_PurgeSlotObjects(FieldSystem *fs, int i){
    if (sOwEnc[i].objId) OwEnc_PurgeID(fs, sOwEnc[i].objId);
}
/* Removes objects with one of our IDs that belong to no slot. */
static void OwEnc_PurgeStrays(FieldSystem *fs){
    int n = MapObjectManager_GetObjectCount(fs->mapObjectMan);
    LocalMapObject *objs = MapObjectManager_GetObjects(fs->mapObjectMan);
    if (!objs) return;
    for (int k = 0; k < n; k++) {
        LocalMapObject *o = &objs[k];
        if (!MapObject_TestFlagsBits(o, MAPOBJECTFLAG_ACTIVE)) continue;
        u32 id = MapObject_GetID(o);
        if (OwEnc_IsOurID(id) && OwEnc_SlotOfID(id) < 0)
            Ow_MapObject_Remove(o);
    }
}


/* ===== map object ===== */
static BOOL OwEnc_BuildObject(FieldSystem *fs, int i){
    OwEnc *e = &sOwEnc[i];
    if (!e->objId) e->objId = OwEnc_RegularID(i);
    if (!OwEnc_ObjValid(e) && OwEnc_PoolUsed() >= sPoolMax) return FALSE;
    OwEnc_PurgeSlotObjects(fs, i);      /* never leave a duplicate behind */
    e->obj = NULL;                      /* the old object is gone: nothing valid to point at */
    LocalMapObject *o = CreateSpecialFieldObject(fs->mapObjectMan, e->curX, e->curZ, e->dir,
                                                 e->sprite, 0 /* still: we drive it by commands */,
                                                 MAP_NOTHING_ID);
    if (!o) return FALSE;
    MapObject_SetID(o, e->objId);
    MapObject_SetType(o, 0);
    MapObject_SetFlagID(o, 0);
    MapObject_SetXRange(o, OWENC_RANGE);
    MapObject_SetYRange(o, OWENC_RANGE);
    /* Sets param 2 bit0 = shiny exactly as the game does for a follower
       (FollowMon_SetObjectParams -> FollowMon_SetObjectShiny). Bit1 is the follower's
       event flag, set only by scrcmd/photo code (sub_02069DEC), and nothing in the shiny
       look reads it, so we no longer force it. The palette itself comes from
       OwEnc_ApplyShiny. */
    FollowPokeMapObjectSetParams(o, e->species, e->form, e->shiny);
    MapObject_SetBits(o, MAPOBJECTFLAG_ACTIVE | MAPOBJECTFLAG_UNK13 | MAPOBJECTFLAG_UNK10); /* UNK10 = KEEP */
    MapObject_ClearBits(o, MAPOBJECTFLAG_UNK8 | MAPOBJECTFLAG_UNK7);
    MapObject_SetFlag29(o, FALSE);      /* TRUE would make it walk-through, like the follower */
    e->obj = o;
    e->walking = 0;
    e->aim = 0;
    return TRUE;
}

/* How many species we can show at once is how many key-table entries we own. ov01_021F9808 builds
   three key tables in MapObjectManager (window = manager + 0x18): 8 texture keys, 8 palette keys
   and 32 model keys -- 48 words in all, inside the fully packed 0x108-byte window buffer
   (map_object.h unk1C[0x108], sizeof(MapObjectManager) 0x12c), so the total cannot be raised, only
   re-tiled. A visible species needs one entry in each table, so the limit is the smallest of our
   three shares. The game reserves 2 texture, 2 palette and GetCount+3 model keys: the 2 comes from
   the same movs r2, #4 at 0x21F946A (patched to 2), which is both the texture game share (r2) and
   the palette game share ([sp,#0x18] in ov01_021F9808); our hook caps GetCount at OWENC_GAME_KEY_MAX
   so the model game share is at most 7. A share is a region: region 0 is the game's, region 1 is
   ours (ov01_021F9968 and ov01_021F9974 are ov01_021F9918 with region 0 and 1), so we load with
   region 1. The shares are words at window+8/+0xc, +0x10/+0x14 and +0x18/+0x1c, so read them at
   runtime: the model share shrinks on maps that preload many objects.
   The tables are re-tiled to 14 texture at window+0x20, 14 palette at window+0x58 and 20 model at
   window+0x90 -- still 48 words, ending exactly at window+0xE0, where ov01_021F9698 puts the next
   field. The three bases are the add r0,#imm8 immediates at 0x21FA200, 0x21FA204 and 0x21FA1FC, the
   init counts are the movs at 0x21F9B08, 0x21F9C2C and 0x21F9D50, and the table sizes are the movs
   at 0x21F946C (texture and palette) and 0x21E6518 (model). That gives us 12 texture, 12 palette
   and 13 model entries. We keep OWENC_KEY_RESERVE of them free in every table for the game's own
   runtime sprites, so we can show 10 species at a time instead of the original 4.
   The pools behind the tables are heap pools in main RAM, not VRAM: ov01_021FC4C4(4, 0x3f, size<<12,
   size) for textures and ov01_021FC4C4(4, 0x40, size<<7, size) for palettes, and
   GF3dGfxRawResMan_Create is a plain num * sizeof(GF_3DGfxRawResObj) allocation. So a bigger table
   only costs heap. The share is a rolling one: the game frees a model when its object leaves the
   window (GF3dGfxRawResMan_FreeObjById + ov01_021FA4F0), so a freed slot is reused by the next
   Pokemon. The game's own followers and NPCs also take entries in our region (ov01_021F9F54 ->
   ov01_021F99D0), so our share is not ours alone: OwEnc_OurKeyFree reads the table itself before we
   ask, because every insert asserts when the region it writes is full (ov01_021F9B54 texture,
   ov01_021F9C34 palette, ov01_021F9D5C model -> GF_AssertFail). That assert is the hang on a route
   with spawns. The game's share is exactly consumed by its two 0xff-terminated preload lists
   (ov01_02207260 texture, ov01_02206CF0 palette), the only writers of the game region, so both were
   truncated to 2 entries to match the patched game share. */
#define OWENC_MODEL_MAX 10  /* species we can show at once: table share minus the reserve below */
#define OWENC_TEX_BASE 0x20  /* texture keys: 14 entries, game share 2 */
#define OWENC_PAL_BASE 0x58  /* palette keys: 14 entries, game share 2 */
#define OWENC_MOD_BASE 0x90  /* model keys: 20 entries, game share = OWENC_GAME_KEY_MAX + 3 */
#define OWENC_KEY_RESERVE 2  /* entries left free in each table for the game's runtime sprites */
#define OWENC_WORD_FREE 0xFF  /* free key in the texture and palette tables (movs r1, #0xff) */
#define OWENC_MODEL_FREE 0xFFFF  /* free key in the model table (literal pool at 0x21F9D58) */

/* TRUE when sprite is already keyed somewhere in the table, or our region still has OWENC_KEY_RESERVE
   free entries so the game can key its own followers and NPCs. Must be checked before Ow_LoadModel:
   the game's insert asserts instead of failing when the region it writes is full, and the caller then
   dereferences NULL. game + ours is the table size, so the whole table is scanned. Entries are words
   (ov01_021F9AB4 does ldr/stmia), so free is the whole sentinel word, not a halfword. */
static BOOL OwEnc_OurKeyFree(u32 w, u32 base, u32 game, u32 ours, u32 sprite, u32 free){
    u32 *k = (u32 *)((u8 *)w + base);
    u32 n = 0;
    for (u32 i = 0; i < game + ours; i++){
        if (k[i] == sprite) return TRUE;
        if (i >= game && k[i] == free) n++;
    }
    return n >= OWENC_KEY_RESERVE;
}

/* True when the sprite's model is in the render window's resource manager. The game's render loop
   assumes it is: when the load fails it asserts (no-op in a release ROM) and then dereferences
   NULL, which hangs the game. So we only build an object for a model we know is there, and retry
   on a later frame otherwise. The window may not be built yet (at map load), hence the guards. */
static BOOL OwEnc_ModelLoaded(FieldSystem *fs, u32 sprite){
    u32 w = (u32)Ow_WindowOfManager(fs->mapObjectMan);
    if (!OWENC_IN_RAM(w)) return FALSE;
    u32 resman = *(u32 *)((u8 *)w + 0xf0);
    if (!OWENC_IN_RAM(resman)) return FALSE;
    if (Ow_ResManGetObjById((void *)resman, (int)sprite)) return TRUE;

    u8 *b = (u8 *)w;
    if (!OwEnc_OurKeyFree(w, OWENC_TEX_BASE, *(u32 *)(b + 8), *(u32 *)(b + 0xc), sprite, OWENC_WORD_FREE)) return FALSE;
    if (!OwEnc_OurKeyFree(w, OWENC_PAL_BASE, *(u32 *)(b + 0x10), *(u32 *)(b + 0x14), sprite, OWENC_WORD_FREE)) return FALSE;
    if (!OwEnc_OurKeyFree(w, OWENC_MOD_BASE, *(u32 *)(b + 0x18), *(u32 *)(b + 0x1c), sprite, OWENC_MODEL_FREE)) return FALSE;

    /* The game loads a model only while its used species count is under the cap (v0 = 10, the
       movs r4,#0xa at 0x21E64FC, patched to 14). Past the cap it stops loading and only looks the
       species up in the entries array; a species that is not there asserts (ov01_021FA4C4). The
       container is at window+0x100, +2 = cap and +4 = used (halfwords). used counts every loaded
       species, ours and the game's own live models, so a new species is safe only while used < cap:
       with cap 10 the game's own models leave us about 4 species, which is the 4 the user sees. */
    u32 c = *(u32 *)((u8 *)w + 0x100);
    if (!OWENC_IN_RAM(c)) return FALSE;
    if (((u16 *)c)[2] >= ((u16 *)c)[1]) return FALSE;

    /* Not there yet: ask for it. ov01_021F9918 returns 0 both when the model is already loaded and
       when the load fails, so the resource manager is the only reliable answer. Region 1 is our share
       of the key tables; region 0 is the game's and would assert past its 2. */
    Ow_LoadModel((void *)w, 1, (int)sprite);
    return Ow_ResManGetObjById((void *)resman, (int)sprite) != NULL;
}

/* ===== shiny look ===== */

/* Shiny is only a palette choice: the billboard gfx block's pltt indices select the model's
   palettes, and index 1 is the shiny one. We keep a heap copy of the block the renderObj
   already uses with every pltt index forced to 1, and point the renderObj at it. Nothing is
   registered in the game's sequence managers, which would mean a NARC read per frame. */
#define OWENC_SHINY_MAX_FRAMES 32  /* sanity bound on a billboard gfx sequence's frame count */
static void OwEnc_ApplyShiny(OwEnc *e){
    if (!OwEnc_ObjValid(e)) return;
    LocalMapObject *o = e->obj;
    u32 ro = *(u32 *)((u8 *)o + 0x108);               /* renderObj */
    if (!OWENC_IN_RAM(ro)) return;                    /* not a render object (yet): write nothing */
    u32 *gfx = (u32 *)((u8 *)ro + 0xa0);              /* the renderObj's gfx block */
    u32 cnt = gfx[3];
    if (!cnt || cnt > OWENC_SHINY_MAX_FRAMES || !OWENC_IN_RAM(gfx[0])) return;
    u32 words = cnt + 1;                              /* the block is 4 + 4*cnt bytes */
    if (!e->shinyBuf){
        u32 *nb = (u32 *)Heap_Alloc(3, words * 4);    /* HEAPID_MAIN_HEAP */
        if (!nb) return;
        e->shinyBuf = (u32)(nb + 1);                  /* startFrame into our copy */
    }
    u32 *buf = (u32 *)e->shinyBuf - 1;
    if (gfx[0] == (u32)(buf + 1)) return;  /* the renderObj already uses our copy: nothing to redo */
    u32 *hdr = (u32 *)gfx[0] - 1;                     /* the count header of the source block */
    if (*hdr != cnt) return;                          /* unusable source: leave it alone */
    for (u32 i = 0; i < words; i++) buf[i] = hdr[i];
    u8 *pltt = (u8 *)buf + 4 + cnt * 3;
    for (u32 i = 0; i < cnt; i++) pltt[i] = 1;        /* pltt 1 = the shiny palette */
    gfx[0] = (u32)(buf + 1);
    gfx[1] = (u32)((u8 *)buf + 4 + cnt * 2);
    gfx[2] = (u32)((u8 *)buf + 4 + cnt * 3);
    gfx[3] = cnt;
}

/* ===== terrain ===== */

static BOOL OwEnc_NearFollower(int x, int z){
    return sHasFol
        && OwEnc_Abs(sFolX - x) <= OWENC_FOLLOWER_DIST
        && OwEnc_Abs(sFolZ - z) <= OWENC_FOLLOWER_DIST;
}
/* -1 = unusable, 0 = land with encounters, 1 = water with encounters. A Pokemon only walks on
   tiles of its own kind; the follower's tile is unusable, so it never walks onto him. */
static int OwEnc_TileKind(FieldSystem *fs, int x, int z){
    if (x < 0 || z < 0) return -1;
    if (OwEnc_NearFollower(x, z)) return -1;
#ifdef OWENC_TILE_BLOCKED
    if (OWENC_TILE_BLOCKED(fs, x, z)) return -1;
#endif
    u8 beh = GetMetatileBehaviorAt(fs, x, z);
    if (!Ow_IsEncTile(beh)) return -1;
    return Ow_IsWaterTile(beh) ? 1 : 0;
}
/* How many of the render window's OWENC_WINDOW_MAX slots we can use on this map. The game's own
   objects (the player, the follower and the event objects in view) take the rest, so the visible
   count changes with the map: a quiet route leaves more room than a town full of NPCs. The game
   asks for its active count plus 3 (player, follower and the battle intro), so those 3 are kept
   out of our share. Counted once per map entry, not every frame. This is the global budget; the
   density rule (see OwEnc_BuildPatches) limits each patch on top of it. */
static void OwEnc_PoolMax(FieldSystem *fs){
    int map = fs->location->mapId;
    if (map == sPoolMap) return;
    sPoolMap = map;
    MapObjectMan *man = fs->mapObjectMan;
    int c = man->object_count;
    LocalMapObject *o = man->objects;
    int used = 0;
    for (int i = 0; i < c; i++)
        if ((o[i].flags & MAPOBJECTFLAG_ACTIVE) && !OwEnc_IsOurID((u32)o[i].id)) used++;
    /* used counts every active object on the whole map, not only the ones in view, so this is the
       conservative worst case. Keys are per species, so the pool is limited by the game's live-object
       capacity (OWENC_WINDOW_MAX), not by the key tables; OWENC_POOL_MAX is the share of that capacity
       we allow ourselves, the rest being reserved for the game's own objects. */
    int room = OWENC_POOL_MAX;
    if (used + 3 < OWENC_WINDOW_MAX) room = OWENC_WINDOW_MAX - used - 3;
    if (room < 1) room = 1;
    sPoolMax = room < OWENC_POOL_MAX ? room : OWENC_POOL_MAX;
}
/* TRUE if (x,z) is closer than minDist to another Pokemon of ours on this map. Two different
   distances are needed: a spawn must keep OWENC_MIN_DIST, but a walk step only has to avoid
   landing on a tile another Pokemon already occupies (OWENC_WANDER_DIST). */
static BOOL OwEnc_Occupied(int x, int z, int minDist){
    for (int i = 0; i < OWENC_SLOTS; i++) {
        if (sOwEnc[i].state == SLOT_EMPTY || (int)sOwEnc[i].mapId != sMap) continue;
        int dx = OwEnc_Abs(sOwEnc[i].curX - x), dz = OwEnc_Abs(sOwEnc[i].curZ - z);
        if ((dx > dz ? dx : dz) < minDist) return TRUE;
    }
    return FALSE;
}

/* The rectangle where Pokemon are placed: the whole map if its size is known, otherwise
   a square around the player. */
/* FieldSystem.mapMatrix sits at offset 0x30 and MapMatrix is {u8 width, u8 height, u8 matrix_id}.
   Used only to clamp the fallback square: without a size, a tile near the edge can index past the
   799-entry map matrix and GetMetatileBehaviorAt reads whatever follows it in the heap. */
static void OwEnc_MapSize(FieldSystem *fs, int *mw, int *mh){
    *mw = 0; *mh = 0;
    u32 mm = *(u32 *)((u8 *)fs + 0x30);
    if (!OWENC_IN_RAM(mm)) return;
    int w = ((u8 *)mm)[0], h = ((u8 *)mm)[1];
    if (w < 1 || h < 1) return;
    /* width and height are in 32x32-tile blocks (MAP_TILES_COUNT_X/Z), but the region works in
       tiles: reporting blocks makes the rectangle smaller than the player's own tile, so w can go
       negative and gf_rand() % (u32)w returns the raw value -- a garbage tile, and w == 0 divides
       by zero. Convert to tiles here. */
    *mw = w * 32;
    *mh = h * 32;
}

static void OwEnc_Region(FieldSystem *fs, int *x0, int *z0, int *w, int *h){
    int mw = OWENC_MAP_W(fs), mh = OWENC_MAP_H(fs);
    if (mw > 0 && mh > 0) { *x0 = 0; *z0 = 0; *w = mw; *h = mh; return; }
    int x = sPX - OWENC_SPAWN_RADIUS, z = sPZ - OWENC_SPAWN_RADIUS;
    if (x < 0) x = 0;
    if (z < 0) z = 0;
    int bw, bh;
    OwEnc_MapSize(fs, &bw, &bh);
    int xe = sPX + OWENC_SPAWN_RADIUS, ze = sPZ + OWENC_SPAWN_RADIUS;
    if (bw > 0 && xe >= bw) xe = bw - 1;
    if (bh > 0 && ze >= bh) ze = bh - 1;
    /* The player must be inside the rectangle, otherwise w/h are negative or zero. */
    if (xe < x) xe = x;
    if (ze < z) ze = z;
    *x0 = x; *z0 = z;
    *w = xe - x + 1;
    *h = ze - z + 1;
}

/* ===== tile patches (density rule) ----
   A patch is a group of touching tiles that share the exact same metatile behaviour. Three
   separated grass patches are three patches; grass next to tall grass is two patches. Each patch
   holds one Pokemon for every OWENC_FILL_DIV tiles of its own size, so a patch of 10 tiles holds 3
   and a patch of 12 tiles holds 4.

   The size is measured on the whole patch, not on a window around the player, so we keep one byte
   per tile with the patch number (0 = not in a patch). The table is built once, when the map is
   entered. If the heap cannot give the bytes, sGroups stays NULL and the density rule is skipped. */

/* Patch a patch number was merged into. Merges only happen while the table is built, so a patch
   number kept on a Pokemon is always a root. */
static int OwEnc_PatchRoot(int g){
    while (sGroups->parent[g] != g) g = sGroups->parent[g];
    return g;
}

/* Patch a tile belongs to, -1 when it is not in the table. Only called with a tile inside the map
   and a table that exists. */
static int OwEnc_PatchOf(int x, int z){
    if (!sGroups) return -1;
    int l = sGroups->label[z * sGroups->w + x];
    return l ? OwEnc_PatchRoot(l - 1) : -1;
}

/* Build the table for the map we are in, one pass in reading order. A tile takes the patch of the
   tile above or of the tile on its left when that tile has the same behaviour; when it touches two
   different patches of the same behaviour, the two are merged. Called once per map entry, so the
   whole map is walked once here. A tile that cannot hold an encounter Pokemon gets no patch; the
   follower is a single tile and must not cut a patch in two, so he is not tested here. */
static void OwEnc_BuildPatches(FieldSystem *fs){
    if (sGroups) Heap_Free((u32 *)sGroups - 1);   /* Heap_Alloc blocks carry a 4-byte header */
    sGroups = NULL;
    int w, h;
    OwEnc_MapSize(fs, &w, &h);
    if (w < 1 || h < 1) return;
    OwEncGroups *g = (OwEncGroups *)Heap_Alloc(HEAP_FIELD2, sizeof(OwEncGroups) + w * h);
    if (!g) return;
    u8 *lab = (u8 *)g + sizeof(OwEncGroups);
    u8 *par = g->parent, *fil = g->fill;
    u16 *til = g->tiles;
    g->label = lab; g->w = w; g->count = 0;
    sGroups = g;   /* OwEnc_PatchRoot reads the table through sGroups, so it must be set here */
    for (int z = 0, t = 0; z < h; z++) {
        for (int x = 0; x < w; x++, t++) {
            u8 beh = GetMetatileBehaviorAt(fs, x, z);
            int p = -1;
            if (Ow_IsEncTile(beh)) {
                u8 la = z ? lab[t - w] : 0;
                u8 lb = x ? lab[t - 1] : 0;
                int a = la ? OwEnc_PatchRoot(la - 1) : -1;
                int b = lb ? OwEnc_PatchRoot(lb - 1) : -1;
                if (a >= 0 && b >= 0 && a != b) { par[b] = a; til[a] += til[b]; p = a; }
                else p = (a >= 0) ? a : b;
                if (p < 0) {
                    if (g->count >= OWENC_GROUP_MAX) continue;
                    p = g->count++; par[p] = p; til[p] = 0; fil[p] = 0;
                }
                til[p]++;
            }
            lab[t] = p + 1;
        }
    }
}

/* A free encounter tile anywhere in the place: the cadence paces the population. The pick is one
   stage of the spawn pipeline, so the tile it finds is kept in the statics for the next frame. */
static BOOL OwEnc_PickSpawnTile(FieldSystem *fs, const u8 *encData){
    int x0, z0, w, h;
    OwEnc_Region(fs, &x0, &z0, &w, &h);
    for (int t = 0; t < OWENC_TRIES; t++) {
        int x = x0 + (int)(gf_rand() % (u32)w);
        int z = z0 + (int)(gf_rand() % (u32)h);
        if (OwEnc_Abs(x - sPX) + OwEnc_Abs(z - sPZ) < OWENC_SPAWN_MIN_DIST) continue;
        if (OwEnc_Occupied(x, z, OWENC_MIN_DIST)) continue;                  /* cheap checks first */
        int k = OwEnc_TileKind(fs, x, z);
        if (k < 0) continue;                 /* not an encounter tile, or the follower's tile */
        /* The game returns before generating when the tile's kind has no rate in this table. Keep
           that guard here: on such a map every slot is empty, so the level roll divides by a range
           built from an empty slot, and the Unown branch reads a Pokedex pointer that was never
           set. Checking it after the pick would burn the whole tick on one unusable tile. */
        if (encData[k == 0 ? 0x00 : 0x01] == 0) continue;
        /* Density rule: the patch already has its share. A tile outside the table (patch cap
           reached, or no table at all) is not limited. */
        int g = OwEnc_PatchOf(x, z);
        if (g >= 0 && sGroups->fill[g] >= sGroups->tiles[g] / OWENC_FILL_DIV) continue;
        sSpawnX = (u16)x; sSpawnZ = (u16)z; sSpawnKind = (u8)k; sSpawnPatch = (u8)(g + 1);
        return TRUE;
    }
    return FALSE;
}

/* ===== follower ===== */

/* The follower walks over our objects, so a Pokemon can end up under him: it steps away, or is
   moved to the nearest free tile of its kind if it cannot. */
static void OwEnc_FollowerPush(FieldSystem *fs){
    if (!sHasFol) return;
    for (int i = 0; i < OWENC_SLOTS; i++) {
        OwEnc *e = &sOwEnc[i];
        if (e->state != SLOT_ACTIVE || !OwEnc_ObjValid(e)) continue;
        if ((int)e->curX != sFolX || (int)e->curZ != sFolZ) continue;

        if (e->walking) {
            Ow_SetHeldMovement(e->obj, e->dir);   /* finish the step on the spot */
            e->walking = 0;
            continue;
        }

        /* Prefer a real step away from the follower. */
        sPushed = 1;
        int best = -1;
        for (int d = 0; d < 4; d++) {
            int nx = e->curX + sDirX[d], nz = e->curZ + sDirZ[d];
            if (nx == sFolX && nz == sFolZ) continue;
            if (nx == sPX && nz == sPZ) continue;
            if (OwEnc_Abs(nx - e->homeX) > OWENC_RANGE || OwEnc_Abs(nz - e->homeZ) > OWENC_RANGE) continue;
            if (OwEnc_TileKind(fs, nx, nz) != (int)e->water) continue;
            u16 ox = e->curX, oz = e->curZ;
            e->curX = 0xFFFF; e->curZ = 0xFFFF;   /* same trick: skip ourselves in the scan */
            BOOL busy = OwEnc_Occupied(nx, nz, OWENC_MIN_DIST);
            e->curX = ox; e->curZ = oz;
            if (busy) continue;
            best = d;
            break;
        }
        if (best >= 0) {
            Ow_SetHeldMovement(e->obj, sStepCmd[best]);
            e->curX = (u16)(e->curX + sDirX[best]);
            e->curZ = (u16)(e->curZ + sDirZ[best]);
            e->dir = (u8)best;
            e->walking = 1;
            e->aim = 0;
            e->idle = OWENC_MOVE_MIN;
            continue;
        }

        /* Boxed: teleport to the nearest free tile of its kind, outside the window
           if possible, so the swap is not seen. */
        int bx = -1, bz = -1, bd = 1, bestDist = 0x7FFFFFFF;
        for (int dz = -2; dz <= 2 && bx < 0; dz++)
            for (int dx = -2; dx <= 2; dx++) {
                int x = sFolX + dx, z = sFolZ + dz;
                if (x < 0 || z < 0) continue;
                if (x == sFolX && z == sFolZ) continue;
                if (x == sPX && z == sPZ) continue;
                if (OwEnc_TileKind(fs, x, z) != (int)e->water) continue;
                int dist = OwEnc_Abs(dx) + OwEnc_Abs(dz);
                if (OwEnc_InWindow(x, z)) dist += 100;
                if (dist < bestDist) {
                    bestDist = dist; bx = x; bz = z;
                    /* face away from the follower, along the dominant axis */
                    if (OwEnc_Abs(bx - sFolX) >= OwEnc_Abs(bz - sFolZ)) bd = (bx < sFolX) ? 2 : 3;
                    else bd = (bz < sFolZ) ? 0 : 1;
                }
            }
        if (bx < 0) { OwEnc_RemoveObj(e); continue; }   /* nowhere to go: hide it */
        e->curX = (u16)bx; e->curZ = (u16)bz;
        e->homeX = (u16)bx; e->homeZ = (u16)bz;
        e->dir = (u8)bd;
        e->walking = 0;
        e->aim = 0;
        e->idle = OWENC_MOVE_MIN;
        if (!OwEnc_BuildObject(fs, i)) continue;   /* pool full: stay object-less, retry later */
    }
}

/* ===== battle ===== */

/* The Pokemon that touched the player stays visible during the battle intro and is removed
   here, once the battle is over and the screen is still black. */
static void OwEnc_ClearGhost(void){
    if (sGhostObj
        && (u32)MapObject_GetGfxID(sGhostObj) == sGhostSprite
        && MapObject_GetParam(sGhostObj, 0) == sGhostSpecies)
        Ow_MapObject_Remove(sGhostObj);
    sGhostObj = NULL;
}

/* Same as the original sub_02050B08: pick the right task for the zone and start it. */
static void OwEnc_StartBattle(FieldSystem *fs, struct BattleSetup *setup){
    sStarted = 1;
    void *flags = Ow_Save_VarsFlags_Get(fs->savedata);
    int effect = Ow_GetWildEffect(setup);
    int bgm = Ow_GetWildBgm(setup);
    void *enc, *task;
    if (Ow_CheckSafari(flags)) {
        enc = Ow_Encounter_New(setup, effect, bgm, NULL); task = OW_TASK_SAFARI;
    } else if (Ow_CheckBugContest(flags)) {
        enc = Ow_Encounter_New(setup, effect, bgm, NULL); task = OW_TASK_BUG;
    } else {
        enc = Ow_WildEncounter_New(setup, effect, bgm, NULL); task = OW_TASK_WILD;
    }
    Ow_CreateTask(fs, task, enc);
}

/* Replaces sub_02050724, called by the battle task right after a battle. The original body is
   kept: it writes the player's party back to the save. */
void OwEnc_BattleDone(struct BattleSetup *setup, FieldSystem *fs){
    if (setup == sPending && sPendingIdx >= 0) {
        OwEnc *e = &sOwEnc[sPendingIdx];
        OwEnc_ClearGhost();
        OwEnc_Forget(e);                      /* whatever the outcome, the Pokemon is gone */
        sPending = NULL; sPendingIdx = -1;
        sFieldGone = 1;
    }
    if (!(setup->battleType & 0x80000000u)) Ow_Sub_0205239C(setup, fs);
}

/* Rebuilds the Pokemon of slot idx and starts a battle against it. */
static BOOL OwEnc_StartContact(FieldSystem *fs, int idx){
    OwEnc *e = &sOwEnc[idx];
    /* Both the battle task and the battle intro need a valid task context and the model loaded in
       the render window; without them the game would hang instead of battle. */
    if (!Ow_ProcessHasParent(fs) || !OwEnc_ModelLoaded(fs, e->sprite)) return FALSE;
    struct PartyPokemon mon;
    struct BattleSetup *s = BattleSetup_New(HEAP_FIELD2, 0);
    if (!s) return FALSE;
    BattleSetup_InitFromFieldSystem(s, fs);
    OwEnc_Rebuild(e, &mon);
    if (!PokeParty_Add(s->party[1], &mon)) { Ow_BattleSetup_Delete(s); return FALSE; }
    sGhostObj = e->obj;
    sGhostSprite = e->sprite;
    sGhostSpecies = e->species;
    e->state = SLOT_BATTLE;
    sPending = s; sPendingIdx = idx;

    /* Free the render window for the battle intro: the game needs its own objects there (player,
       follower, battle scene), so every other record gives its object back. The records stay in
       memory and get their objects again from OwEnc_Populate once the field is rebuilt. */
    for (int i = 0; i < OWENC_SLOTS; i++)
        if (i != idx) OwEnc_RemoveObj(&sOwEnc[i]);

    OwEnc_StartBattle(fs, s);
    return TRUE;
}

/* ===== sync ===== */

/* Despawn: a place is deleted when the player leaves it (new map, building, cave exit). The
   records are freed and the place is regenerated from scratch on the next entry. */
static void OwEnc_DespawnPlace(FieldSystem *fs, int map){
    OwEnc_PurgeStrays(fs);
    sMap = map;
    sSpawnClock = 0;  /* the place is empty: it is filled again on entry */

    /* New place: the patches are different, so the table is rebuilt. Records of the other place are
       freed (their group number belongs to the old table, so it is cleared first), and the Pokemon
       that were already here (coming back to the same map) are counted again in the new table. */
    OwEnc_BuildPatches(fs);
    for (int i = 0; i < OWENC_SLOTS; i++) {
        OwEnc *e = &sOwEnc[i];
        if (e->state == SLOT_EMPTY) continue;
        if (e->mapId != (u16)map) { e->group = 0; OwEnc_FreeSlot(e); continue; }
        int g = OwEnc_PatchOf(e->curX, e->curZ);
        if (g < 0) continue;
        e->group = (u8)(g + 1);
        sGroups->fill[g]++;
    }
}

static void OwEnc_Sync(FieldSystem *fs){
    int map = fs->location->mapId;
    MapObjectMan *man = fs->mapObjectMan;

    /* Field rebuilt (after any battle, or a fresh field): every pointer is stale, so forget
       them first; what is still in memory gets its object back from OwEnc_Populate. */
    if (sObjMan != man || sFieldGone) {
        OwEnc_ClearGhost();
        for (int i = 0; i < OWENC_SLOTS; i++) {
            sOwEnc[i].obj = NULL;
            sOwEnc[i].walking = 0;
            sOwEnc[i].aim = 0;
        }
        for (int i = 0; i < OWENC_SLOTS; i++) {
            OwEnc *e = &sOwEnc[i];
            if (e->state == SLOT_EMPTY) continue;
            OwEnc_PurgeSlotObjects(fs, i);
            if (e->state == SLOT_BATTLE) OwEnc_Forget(e);       /* outcome unknown: it is gone */
        }
        OwEnc_PurgeStrays(fs);
        sObjMan = man; sFieldGone = 0;
        sPending = NULL; sPendingIdx = -1;
    }
    if (sMap != map) OwEnc_DespawnPlace(fs, map);
}

/* ===== moving ===== */

/* Random walk with real step animation: the game moves the object, we pick the direction after
   checking the destination and poll for the end of each command. A Pokemon whose step would
   land on the player turns first, waits, then offers a battle. */
static void OwEnc_Wander(FieldSystem *fs){
    for (int i = 0; i < OWENC_SLOTS; i++) {
        OwEnc *e = &sOwEnc[i];
        if (e->state != SLOT_ACTIVE || !OwEnc_ObjValid(e)) continue;

        if (e->walking) {
            if (!Ow_ClearHeldIfActive(e->obj)) continue;       /* command still in progress */
            e->walking = 0;
            /* Re-read the real tile in case the step was blocked; only trust values close to
               what we expect, in case the getters use another unit. */
            int rx = (int)MapObject_GetCurrentX(e->obj);
            int rz = (int)MapObject_GetCurrentY(e->obj);
            if (OwEnc_Abs(rx - e->curX) <= 1 && OwEnc_Abs(rz - e->curZ) <= 1) {
                e->curX = (u16)rx; e->curZ = (u16)rz;
            }
        }
        if (e->idle > 0) { e->idle--; continue; }
        e->idle = (u8)(OWENC_MOVE_MIN + gf_rand() % OWENC_MOVE_RAND);

        /* It turned towards the player earlier: now it hits him, if he is still in front of it. */
        if (e->aim) {
            e->aim = 0;
            if (e->curX + sDirX[e->dir] == sPX && e->curZ + sDirZ[e->dir] == sPZ) {
                OwEnc_Offer(i, OWENC_PRIO_BUMP);
                continue;
            }
        }

        u8 nd = (u8)(gf_rand() & 3);
        if (gf_rand() % 100 < OWENC_CHASE_PERCENT) {           /* bias towards the player */
            int ddx = sPX - e->curX, ddz = sPZ - e->curZ;
            if (OwEnc_Abs(ddx) > OwEnc_Abs(ddz)) nd = ddx < 0 ? 2 : 3;
            else                                 nd = ddz < 0 ? 0 : 1;
        }
        int nx = e->curX + sDirX[nd], nz = e->curZ + sDirZ[nd];

        /* The step would land on the player: turn first, then hit him. */
        if (nx == sPX && nz == sPZ) {
            if (e->dir == nd) {
                OwEnc_Offer(i, OWENC_PRIO_BUMP);               /* already facing him */
            } else {
                Ow_SetHeldMovement(e->obj, nd);                /* commands 0-3 turn on the spot */
                e->dir = nd;
                e->walking = 1;
                e->aim = 1;
                e->idle = OWENC_TURN_DELAY;
            }
            continue;
        }

        if (nx < 0 || nz < 0
            || OwEnc_Abs(nx - e->homeX) > OWENC_RANGE || OwEnc_Abs(nz - e->homeZ) > OWENC_RANGE
            || OwEnc_TileKind(fs, nx, nz) != (int)e->water) continue;   /* also blocks the follower's tile */

        /* Distance check against the others: OwEnc_Occupied scans every record including this
           one, so park our own tile out of the way while it checks. Only the destination tile
           itself is blocked (OWENC_WANDER_DIST), otherwise the density rule makes every step
           land within OWENC_MIN_DIST and no Pokemon can move. */
        u16 ox = e->curX, oz = e->curZ;
        e->curX = 0xFFFF; e->curZ = 0xFFFF;
        BOOL busy = OwEnc_Occupied(nx, nz, OWENC_WANDER_DIST);
        e->curX = ox; e->curZ = oz;
        if (busy) continue;

        Ow_SetHeldMovement(e->obj, sStepCmd[nd]);
        e->curX = (u16)nx; e->curZ = (u16)nz;     /* reserve the destination right away */
        e->dir = nd;
        e->walking = 1;
    }
}

/* ===== player contact ===== */

/* Index of the slot with a ready object on tile (x,z), or -1 */
static int OwEnc_At(FieldSystem *fs, int x, int z){
    for (int i = 0; i < OWENC_SLOTS; i++) {
        OwEnc *e = &sOwEnc[i];
        if (e->state == SLOT_ACTIVE && e->mapId == fs->location->mapId && OwEnc_ObjValid(e)
            && e->curX == x && e->curZ == z) return i;
    }
    return -1;
}

/* The player starts a fight by pushing: he must face the Pokemon, and the first frame that
   registers the push is enough. The game's own step counter only ticks while walking, which is
   why holding the direction used to be required. */
static void OwEnc_PlayerContact(FieldSystem *fs, u16 heldKeys){
    int here = OwEnc_At(fs, sPX, sPZ);
    if (here >= 0) { OwEnc_Offer(here, OWENC_PRIO_PLAYER); return; }   /* standing on it */

    int dir = Ow_PlayerFacing(fs->playerAvatar);
    int idx = -1;
    if (dir >= 0 && dir < 4 && (heldKeys & sDirKey[dir]))
        idx = OwEnc_At(fs, sPX + sDirX[dir], sPZ + sDirZ[dir]);
    if (idx < 0) return;
    OwEnc_Offer(idx, OWENC_PRIO_PLAYER);
}

/* ===== spawn ===== */

/* Turns the Pokemon the generator produced into a slot on the tile picked by OwEnc_PickSpawnTile;
   the object is created later by OwEnc_Populate. TRUE if a record was filled. */
static BOOL OwEnc_TrySpawn(FieldSystem *fs, struct BattleSetup *setup){
    struct PartyPokemon *mon = Party_GetMonByIndex(setup->party[1], 0);
    /* The generated Pokemon is still encrypted at this point: GetMonData reads the raw blocks and
       returns garbage, as OwEnc_Pack explains. Read the species through the box accessor. */
    int species = GetBoxMonData(&mon->box, MON_DATA_SPECIES, 0);
    if (species <= 0 || species > OWENC_MAX_SPECIES) return FALSE;   /* no follower sprite */

    /* Shininess is whatever the game's own roll produced: we never touch the PID or the OT ID,
       so the overworld look and the caught Pokemon agree. Shinies are exempt from the budget. */
    BOOL shiny = MonIsShiny(mon);
    if (!shiny && OwEnc_Count(FALSE) >= sPoolMax) return FALSE;
    int slot = OwEnc_FindFree();
    if (slot < 0) return FALSE;

    OwEnc *e = &sOwEnc[slot];
    OwEnc_Forget(e);
    OwEnc_Pack(e, mon);
    e->sprite = FollowingPokemon_GetSpriteID(e->species, e->form, e->gender);
    e->mapId = (u16)fs->location->mapId;
    e->water = sSpawnKind;
    if (sSpawnPatch) { e->group = sSpawnPatch; sGroups->fill[sSpawnPatch - 1]++; }  /* its patch now has one of its slots */
    e->homeX = e->curX = sSpawnX;
    e->homeZ = e->curZ = sSpawnZ;
    e->dir = (u8)(gf_rand() & 3);
    e->idle = OWENC_SPAWN_STILL;      /* it appears still: it walks only after the spawn delay */
    e->state = SLOT_ACTIVE;
    e->objId = OwEnc_RegularID(slot);
    return TRUE;
}

/* Second stage of the spawn: the game's own generator, run for the tile picked on the previous
   frame. This is the same code the step check runs (slot roll, level, nature, shininess), but
   reached directly instead of through the step counter, so a Pokemon can appear without the player
   walking. The rate dice roll, the repel/flute/held-item/ability effects and the roamer check are
   skipped on purpose: a spawn is not a battle. A BattleSetup is still needed to carry the generated
   Pokemon, so we make one on the field heap and free it right after. */
static void OwEnc_GenStage(FieldSystem *fs){
    const u8 *encData = Ow_GetLoadedEncTable(fs);   /* encounter table of the place we are in */
    sSpawnStage = 0;
    if (encData != sSpawnEnc) return;               /* the place changed since the pick: stale tile */

    struct Party *party = Ow_PartyGet(fs->savedata);
    if (party == NULL) return;
    struct PartyPokemon *lead = Party_GetMonByIndex(party, 0);
    if (lead == NULL) return;

    struct BattleSetup *setup = NULL;
    Ow_CreateBattleSetup(fs, 0, &setup);            /* ENCOUNTER_CONTEXT_REGULAR: BATTLE_TYPE_NONE */
    if (setup == NULL) return;
    Ow_BattleSetup_InitFS(setup, fs);
    Ow_GenState_Init(fs, lead, encData, sGenState);

    BOOL found;
    if (sSpawnKind == 0) {
        Ow_SlotArray_InitLand(encData, sEncSlots);
        Ow_Slots_UpdateLand(fs, encData, sEncSlots, sEncSlots + 1);
        Ow_Slots_UpdateSounds(fs, encData, sEncSlots);
        found = Ow_GenerateLandEnc(fs, lead, setup, encData, sEncSlots, sGenState);
    } else {
        const struct EncounterDataSlot *surf = (const struct EncounterDataSlot *)(encData + 0x64);
        for (int i = 0; i < OWENC_SURF_COUNT; i++) {
            sEncSlots[i].species  = surf[i].species;
            sEncSlots[i].maxLevel = surf[i].level_max;
            sEncSlots[i].minLevel = surf[i].level_min;
        }
        Ow_Slots_UpdateSurf(fs, encData, sEncSlots);
        found = Ow_GenerateSurfEnc(fs, lead, setup, sEncSlots, sGenState, 0);
    }

    if (found) OwEnc_TrySpawn(fs, setup);
    Ow_BattleSetup_Delete(setup);
}

/* Gives an object to one record per frame. The model load and the object build are the two most
   expensive parts of showing a Pokemon, so they are done in different frames: this frame loads the
   model, the next builds the object for the record remembered in sPopSlot. The same pass ages the
   retries and finds the nearest record without an object, so the records are walked once per frame
   instead of once per object built. */
static void OwEnc_Populate(FieldSystem *fs){
    int map = fs->location->mapId;
    if (sPopSlot != 0xFF) {                     /* the model was loaded last frame: build the object */
        int i = sPopSlot;
        sPopSlot = 0xFF;
        OwEnc *e = &sOwEnc[i];
        /* The record may have been freed in the meantime (battle, or a different map). */
        if (e->state == SLOT_ACTIVE && !OwEnc_BuildObject(fs, i)) e->retry = OWENC_RETRY_FRAMES;
        return;
    }
    int best = -1, bestD = 0x7FFFFFFF, far = -1, farD = -1, used = 0;
    for (int i = 0; i < OWENC_SLOTS; i++) {
        OwEnc *e = &sOwEnc[i];
        if (e->state != SLOT_ACTIVE || e->mapId != map) continue;
        if (e->retry > 0) { e->retry--; continue; }        /* waiting its turn: let another go first */
        int d = OwEnc_Dist(e);
        if (OwEnc_ObjValid(e)) {                           /* already visible: count it, and remember the
                                                              farthest one in case we need its place */
            used++;
            if (d > farD) { farD = d; far = i; }
            continue;
        }
        if (d < bestD) { bestD = d; best = i; }            /* the pool goes to whoever the window
                                                              would show anyway */
    }
    if (best < 0) return;
    /* Pool full: take an object back from a record much farther away so that the visible set
       follows the player instead of staying where it was first built. */
    if (used >= sPoolMax && far >= 0 && farD - bestD >= OWENC_POOL_SWAP) OwEnc_RemoveObj(&sOwEnc[far]);
    if (!OwEnc_ModelLoaded(fs, sOwEnc[best].sprite)) { sOwEnc[best].retry = OWENC_RETRY_FRAMES; return; }
    sPopSlot = (u8)best;
}

/* The place is filled one Pokemon at a time: one attempt every OWENC_SPAWN_INTERVAL frames (2 s at
  30 fps). Each frame runs at most one stage of the pipeline: the pick here, the generator on the next frame, then the model load and the object build in the two
   frames after that (see OwEnc_Populate). A failed attempt (no free tile, no room left in the
   budget, a species without a sprite) waits for the next tick. */
static void OwEnc_SpawnTick(FieldSystem *fs){
    if (sSpawnStage) { OwEnc_GenStage(fs); return; }
    if (!Ow_HasWildEncounters(sMap) || OwEnc_SpecialZone(fs)) return;
    if (OwEnc_Count(FALSE) >= sPoolMax) return;
    if (sSpawnClock > 0) { sSpawnClock--; return; }
    sSpawnClock = OWENC_SPAWN_INTERVAL;
    const u8 *encData = Ow_GetLoadedEncTable(fs);
    if (!encData) return;
    sSpawnEnc = encData;
    if (OwEnc_PickSpawnTile(fs, encData)) sSpawnStage = 1;
}

/* ===== save ===== */

/* Replaces FieldSystem_SyncMapObjectsToSaveEx. The save's map-object array is a fixed
   64-entry list and the original writes every ACTIVE object into it, which our 96-slot manager
   could overflow. Ours skips our Pokemon: none of them is saved. */
/* The hook uses r3, so the caller's count never arrives (r3 holds the address we were jumped
   to); the list is exactly 64 entries and the only caller passes 64, so the count is fixed. */
void OwEnc_SyncToSaveEx(FieldSystem *fs, void *manager, SavedMapObject *savedObjects){
    s32 count = 64;
    int n = MapObjectManager_GetObjectCount(manager);
    LocalMapObject *obj = MapObjectManager_GetObjects(manager);
    for (int i = 0; i < n && count > 0; i++, obj++){
        if (!MapObject_TestFlagsBits(obj, MAPOBJECTFLAG_ACTIVE)) continue;
        if (OwEnc_IsOurID(MapObject_GetID(obj))) continue;   /* ours are never saved */
        SavedMapObject_InitFromLocalMapObject(fs, obj, savedObjects);
        savedObjects++;
        count--;
    }
    if (count > 0) {
        u8 *p = (u8 *)savedObjects;
        u32 bytes = (u32)count * (u32)sizeof(SavedMapObject);
        for (u32 i = 0; i < bytes; i++) p[i] = 0;
    }
}

/* ===== manager ===== */

/* Replaces MapObjectManager_Init so field maps get OWENC_MANAGER_OBJECTS slots. The game's own
   request is never reduced: MapObject_CreateFromInitArgs asserts when an object event cannot get a
   slot, so stealing one of the game's slots hangs the game. Only our share is trimmed to what the
   FIELD2 heap can really hold, with OWENC_HEAP_RESERVE left for the map matrix, map events, battle
   setups and AllocMonZeroed that share the heap. */
void *OwEnc_ManagerInit(FieldSystem *fs, u32 count, u32 priority){
    u32 free = GF_ExpHeap_FndGetTotalFreeSize(HEAP_FIELD2);
    /* The patch table (one byte per tile plus its own arrays) comes from the same heap as the
       manager slots, so it must be reserved here or OwEnc_BuildPatches gets nothing. When the map
       size is not known yet, the fallback square around the player is the worst case. */
    int w, h;
    OwEnc_MapSize(fs, &w, &h);
    u32 tiles = (w > 0 && h > 0) ? (u32)w * h
                                 : (u32)(2 * OWENC_FALLBACK_RADIUS + 1) * (2 * OWENC_FALLBACK_RADIUS + 1);
    u32 reserve = OWENC_HEAP_RESERVE + tiles + (u32)sizeof(OwEncGroups);
    u32 budget = free > reserve ? free - reserve : 0;
    u32 fit = budget / OWENC_LMO_SIZE;
    u32 extra = fit > count ? fit - count : 0;
    /* Only the pool can hold an object, so the manager never needs more than OWENC_WINDOW_MAX
       slots of ours. Keeping it at OWENC_SLOTS would make every game loop that walks the manager
       (sub_02060BFC, sub_02060CA8, ov01_021F97BC, ov02_0224F4BC) walk 164 entries instead of 96. */
    if (extra > OWENC_WINDOW_MAX) extra = OWENC_WINDOW_MAX;
    u32 n = count + extra;
    void *m = MapObjectManager_New(n);
    if (!m) return NULL;
    MapObjectManager_SetFieldSystem(m, fs);
    MapObjectManager_SetObjectCount(m, n);
    MapObjectManager_SetPriority(m, priority);
    return m;
}

/* ===== frame ===== */

/* Runs every frame, from the hook inside FieldInput_Process: sync the field and the place,
   give the records their map objects, spawn on the clock, apply the shiny look, then pick the
   battle candidate from the follower push, the player push and the walk. */
void OwEnc_Frame(FieldSystem *fs, u16 newKeys, u16 heldKeys){
    (void)newKeys;
    if (Ow_CheckPalPark(Ow_Save_VarsFlags_Get(fs->savedata)) == 1) return;
    OwEnc_Ensure();
    if (!sOwEnc) return;
    OwEnc_UpdatePlayer(fs);
    OwEnc_Sync(fs);
    OwEnc_PoolMax(fs);       /* the room we have in the window changes with the map */
    OwEnc_Populate(fs);      /* give the records their map objects */
    OwEnc_SpawnTick(fs);     /* one new Pokemon per tick, no player step needed */
    for (int i = 0; i < OWENC_SLOTS; i++)
        if (sOwEnc[i].state == SLOT_ACTIVE && sOwEnc[i].shiny) OwEnc_ApplyShiny(&sOwEnc[i]);

    sHitIdx = -1; sHitPrio = 0; sHitTies = 0;
    sPushed = 0;
    OwEnc_FollowerPush(fs);                              /* the follower walks over our objects */
    OwEnc_PlayerContact(fs, heldKeys);
    OwEnc_Wander(fs);                                    /* may offer more candidates */
    if (sHitIdx >= 0 && !(sPushed && sHitPrio == OWENC_PRIO_PLAYER))
        OwEnc_StartContact(fs, sHitIdx);
}

/* Placed at 021E6B9C, replacing: bl sub_0205DD94 / adds r7,r0 / ldr r0,[r4,#12].
   Calls OwEnc_Frame(fs, newKeys, heldKeys), then performs the replaced instructions. */
__attribute__((naked)) void OwEnc_FrameHook(void){
    __asm__ volatile(
        ".thumb\n"
        "push {r0-r3}\n"
        "mov r0, r4\n"              /* r4 = FieldSystem; r1, r2 = keys stay as they were */
        "ldr r3, =OwEnc_Frame\n"
        "blx r3\n"
        "pop {r0-r3}\n"
        "ldr r3, =0x0205DD95\n"     /* original sub_0205DD94, Thumb */
        "blx r3\n"
        "mov r7, r0\n"
        "ldr r0, [r4, #12]\n"
        "ldr r3, =0x021E6BA5\n"     /* resume at 021E6BA4, Thumb */
        "bx r3\n"
        ".ltorg\n"
    );
}

/* Replaces sub_02050B08(fs, setup): the game calls it to start a wild battle. */
void OwEnc_Capture(FieldSystem *fs, struct BattleSetup *setup){
    OwEnc_Ensure();
    if (sInCheck && setup->battleType == 0 && !OwEnc_SpecialZone(fs)) {
        Ow_BattleSetup_Delete(setup);                  /* regular step encounter: replaced by spawns */
        return;
    }
    OwEnc_StartBattle(fs, setup);                      /* roamers, Safari, Bug Contest */
}



/* Replaces FieldSystem_CheckWildEncounter, called at the end of every player step.
   Regular encounters no longer start from here; it only lets roamers through. */
BOOL OwEnc_CheckWildEncounter(FieldSystem *fs){
    u16 *inhibit = (u16 *)((u8 *)fs + 0x7E);
    if (*inhibit < 0xFFFF) (*inhibit)++;
    int x, z;
    Ow_GetStandingTileCoords(fs, &x, &z);
    if (Ow_CheckPalPark(Ow_Save_VarsFlags_Get(fs->savedata)) == 1) {
        if (Ow_CatchingShow_Check(fs, x, z) == 1) {
            Ow_PalParkBattle(fs, Ow_CatchingShow_GetData(fs));
            return TRUE;
        }
        return FALSE;
    }
    if (!Ow_HasWildEncounters(fs->location->mapId)) return FALSE;
    OwEnc_Ensure();
    if (!sOwEnc) return FALSE;
    sStarted = 0; sInCheck = 1;
    Ow_Perform(fs);
    sInCheck = 0;
    return sStarted;
}